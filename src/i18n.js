let current = store.get('lang', 'uz') === 'en' ? 'en' : 'uz';

export const lang = () => current;

export function setLang(l) {
  current = l === 'en' ? 'en' : 'uz';
  store.set('lang', current);
  document.documentElement.lang = current;
}

// t('list.found', { n: 3 }) → "3 ta joy topildi"
export function t(key, vars = {}) {
  const s = STR[current][key] ?? STR.uz[key] ?? key;
  return s.replace(/\{(\w+)\}/g, (_, k) => (vars[k] ?? `{${k}}`));
}

// Qidiruv uchun kalitning ikkala tildagi matni
export const tBoth = (key) => [STR.uz[key], STR.en[key]].filter(Boolean);

// Ma'lumot maydonining tarjimasi: obj.en?.field bo'lsa EN rejimda shuni oladi
export function tr(obj, field) {
  if (current === 'en' && obj.en && obj.en[field]) return obj.en[field];
  return obj[field];
}
